"""Compute metrics and figures from every predictions file in results/predictions/.

For each model and split the low-FPR threshold is chosen on the validation
set (target FPR 1% by default) and applied unchanged to the test set.

Writes results/metrics.json, results/metrics.md and figures in results/figures/.

Usage:
    python scripts/evaluate.py
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from phishdet import plots
from phishdet.evaluation import evaluate, load_predictions

ROOT = Path(__file__).resolve().parents[1]
PRED = ROOT / "results" / "predictions"
FIG = ROOT / "results" / "figures"

LABELS = {"tfidf_lr": "TF-IDF + LR", "minilm_lr": "MiniLM + LR"}


def fmt(x: float, pct: bool = False) -> str:
    return f"{x:.1%}" if pct else f"{x:.4f}"


def table(results: dict, split: str) -> list[str]:
    rows = [
        "| model | ROC-AUC | PR-AUC | P @0.5 | R @0.5 | F1 @0.5 | threshold | P @thr | R @thr | F1 @thr | FPR @thr | FP / FN @thr | Brier | ECE |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, r in results.items():
        if r["split"] != split:
            continue
        t = r["test"]
        h, lo = t["at_0.5"], t["at_low_fpr"]
        rows.append(
            f"| {LABELS.get(r['model'], r['model'])} | {fmt(t['roc_auc'])} | {fmt(t['pr_auc'])} | "
            f"{fmt(h['precision'])} | {fmt(h['recall'])} | {fmt(h['f1'])} | {lo['threshold']:.3f} | "
            f"{fmt(lo['precision'])} | {fmt(lo['recall'])} | {fmt(lo['f1'])} | {fmt(lo['fpr'], True)} | "
            f"{lo['fp']} / {lo['fn']} | {fmt(t['brier'])} | {fmt(t['ece'])} |"
        )
    return rows


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--target-fpr", type=float, default=0.01)
    args = ap.parse_args(argv)

    results: dict[str, dict] = {}
    parts_by_name = {}
    for csv_path in sorted(PRED.glob("*.csv")):
        name = csv_path.stem  # e.g. tfidf_lr_split
        model, split = name.rsplit("_", 1)
        parts = load_predictions(csv_path)
        parts_by_name[name] = parts
        results[name] = {"model": model, "split": split, **evaluate(parts, args.target_fpr)}
        print(f"{name}: test ROC-AUC {results[name]['test']['roc_auc']:.4f}")

    (ROOT / "results" / "metrics.json").write_text(json.dumps(results, indent=2) + "\n")

    lines = [
        "# Metrics",
        "",
        f"Generated by `scripts/evaluate.py`. Threshold chosen on validation for FPR <= {args.target_fpr:.0%}, "
        "then applied to test. P = precision, R = recall.",
        "",
        "## Stratified group split (test)",
        "",
        *table(results, "split"),
        "",
        "## Time split: train on phishing before 2020, test on 2020-2025 (test)",
        "",
        *table(results, "time"),
        "",
        "## Per-group rates on the stratified test set (at the low-FPR threshold)",
        "",
        "| model | group | n | rate |",
        "|---|---|---|---|",
    ]
    for name, r in results.items():
        if r["split"] != "split":
            continue
        for g, v in r["test_by_group"].items():
            key = "fpr_at_low_fpr" if g.startswith("legit") else "recall_at_low_fpr"
            what = "FPR" if g.startswith("legit") else "recall"
            lines.append(f"| {LABELS.get(r['model'], r['model'])} | {g} | {v['n']} | {what} {v[key]:.1%} |")
    lines += ["", "## SpamAssassin spam side set (never trained on)", "", "| model | split | n | flagged @thr | flagged @0.5 | median score |", "|---|---|---|---|---|---|"]
    for name, r in results.items():
        sp = r.get("spam_side_set")
        if sp:
            lines.append(
                f"| {LABELS.get(r['model'], r['model'])} | {r['split']} | {sp['n']} | {sp['flagged_at_low_fpr']:.1%} | "
                f"{sp['flagged_at_0.5']:.1%} | {sp['median_score']:.3f} |"
            )
    (ROOT / "results" / "metrics.md").write_text("\n".join(lines) + "\n")

    # figures
    for split, suffix in (("split", " - stratified test"), ("time", " - time-split test")):
        names = [n for n in results if results[n]["split"] == split]
        if not names:
            continue
        curves = {LABELS.get(results[n]["model"], n): (parts_by_name[n]["test"].y, parts_by_name[n]["test"].s) for n in names}
        plots.roc_pr(curves, FIG / f"roc_pr_{split}.png", suffix)
        mats = {LABELS.get(results[n]["model"], n): {k: results[n]["test"]["at_low_fpr"][k] for k in ("tp", "fp", "tn", "fn")} for n in names}
        plots.confusion_matrices(mats, FIG / f"confusion_{split}.png", f"threshold set for {args.target_fpr:.0%} FPR on validation")
        if split == "split":
            plots.calibration(curves, FIG / "calibration_split.png")
        else:
            series = {LABELS.get(results[n]["model"], n): results[n]["test_recall_by_year"] for n in names}
            plots.recall_by_year(series, FIG / "time_split_recall_by_year.png", "Time split: recall on newer phishing, by year")
    print("wrote results/metrics.json, results/metrics.md and figures")
    return 0


if __name__ == "__main__":
    sys.exit(main())
